//! `spatial` mode: PhotoCraft's Camera Raw whole-frame stages -- dehaze, Highlights/Shadows
//! (local_tone), Contrast/Texture/Clarity and Whites/Blacks -- on small synthetic frames, for
//! PixCake's port in gpu/render/src/camera_raw_spatial.cpp.  Only those sliders are set, so
//! develop runs stages 2, 3 and 3b and the final clip to 0..1.

use photocraft_algo::camera_raw::{CameraRaw, develop};

use crate::{COMMIT, f};

/// Shortest round-trip decimal of each value (Rust's `{:e}`), as C++ float literals.
fn short(v: &[f32]) -> String {
    v.iter().map(|x| format!("{x:e}f")).collect::<Vec<_>>().join(",")
}

/// The frames, as (name, width, height, pixel function); the C++ test rebuilds them.
pub fn frames() -> Vec<(&'static str, usize, usize, fn(usize, usize, usize, usize) -> [f32; 4])> {
    fn detail(x: usize, y: usize, w: usize, h: usize) -> [f32; 4] {
        let edge = if x * 2 > w { 0.35 } else { 0.0 };
        let check = if (x / 3 + y / 3) % 2 == 0 { 0.08 } else { -0.08 };
        [0.1 + 0.5 * x as f32 / (w - 1) as f32 + edge, 0.15 + 0.6 * y as f32 / (h - 1) as f32 + check, 0.3 + edge * 0.5 - check, 1.0]
    }
    fn grey(_: usize, _: usize, _: usize, _: usize) -> [f32; 4] {
        [0.5, 0.5, 0.5, 1.0]
    }
    fn block(x: usize, y: usize, _: usize, _: usize) -> [f32; 4] {
        if (8..17).contains(&x) && (4..11).contains(&y) { [0.97, 0.95, 0.9, 1.0] } else { [0.25, 0.3, 0.35, 1.0] }
    }
    vec![("detail", 24, 16, detail), ("grey", 24, 16, grey), ("block", 24, 16, block), ("strip", 840, 6, detail)]
}

fn cases() -> Vec<(&'static str, CameraRaw)> {
    let c = |f: &dyn Fn(&mut CameraRaw)| {
        let mut p = CameraRaw::default();
        f(&mut p);
        p
    };
    vec![
        ("dehaze 30", c(&|p| p.dehaze = 30.0)),
        ("dehaze -100", c(&|p| p.dehaze = -100.0)),
        ("contrast 40", c(&|p| p.contrast = 40.0)),
        ("texture 100", c(&|p| p.texture = 100.0)),
        ("texture -50 scale 0.5", c(&|p| {
            p.texture = -50.0;
            p.pixel_scale = 0.5;
        })),
        ("clarity 100", c(&|p| p.clarity = 100.0)),
        ("clarity -50 contrast 40 texture -30", c(&|p| {
            p.clarity = -50.0;
            p.contrast = 40.0;
            p.texture = -30.0;
        })),
        ("shadows 100", c(&|p| p.shadows = 100.0)),
        ("highlights -100", c(&|p| p.highlights = -100.0)),
        ("shadows -50 highlights 50", c(&|p| {
            p.shadows = -50.0;
            p.highlights = 50.0;
        })),
        ("whites 100", c(&|p| p.whites = 100.0)),
        ("blacks -100", c(&|p| p.blacks = -100.0)),
        ("whites -50 blacks 50", c(&|p| {
            p.whites = -50.0;
            p.blacks = 50.0;
        })),
        ("all", c(&|p| {
            p.dehaze = 40.0;
            p.shadows = 60.0;
            p.highlights = -60.0;
            p.contrast = 25.0;
            p.texture = 30.0;
            p.clarity = 40.0;
            p.whites = 20.0;
            p.blacks = -20.0;
        })),
    ]
}

pub fn run() {
    println!("// PhotoCraft {COMMIT} crates/algo/src/camera_raw.rs develop (float = false), sRGB encoding:");
    println!("// whole-frame stages only.  Frames: see tools/photocraft_vectors/src/spatial.rs frames(); the");
    println!("// 840 x 6 strip keeps every 15th pixel.  Generated by tools/photocraft_vectors spatial -- do not edit.");
    println!("struct SpatialCase {{ const char* frame; const char* name; float dehaze, contrast, texture, clarity, shadows, highlights, whites, blacks, pixel_scale; int stride; std::vector<float> out; }};");
    println!("const SpatialCase kSpatial[] = {{");
    for (frame, w, h, pixel) in frames() {
        for (name, p) in cases() {
            let mut px: Vec<[f32; 4]> = (0..w * h).map(|i| pixel(i % w, i / w, w, h)).collect();
            develop(&mut px, w, h, &p, false);
            let stride = if w * h > 2000 { 15 } else { 1 };
            let out: Vec<f32> = px.iter().step_by(stride).flat_map(|q| [q[0], q[1], q[2]]).collect();
            let s = [p.dehaze, p.contrast, p.texture, p.clarity, p.shadows, p.highlights, p.whites, p.blacks, p.pixel_scale].map(f);
            println!("{{\"{frame}\", \"{name}\", {}, {stride}, {{{}}}}},", s.join(", "), short(&out));
        }
    }
    println!("}};");
}
