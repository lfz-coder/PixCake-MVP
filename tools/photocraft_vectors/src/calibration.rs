//! `calibration` mode: PhotoCraft's Camera Raw stage 1b (Calibration primaries: hue and
//! saturation of the red, green and blue primaries in linear light), which PixCake ports in
//! gpu/render/src/camera_raw.cpp.  develop with float = false on the per-pixel inputs; stage 1
//! (temperature, exposure) is set in some cases to put the calibration after it.

use photocraft_algo::camera_raw::{CameraRaw, calibration_weights, develop};

use crate::{COMMIT, f, inputs, list};

fn cases() -> Vec<(&'static str, CameraRaw)> {
    let c = |hue: [f32; 3], sat: [f32; 3]| CameraRaw { calibration_hue: hue, calibration_sat: sat, ..CameraRaw::default() };
    vec![
        ("red hue 50", c([50.0, 0.0, 0.0], [0.0; 3])),
        ("green hue -70", c([0.0, -70.0, 0.0], [0.0; 3])),
        ("blue hue 100", c([0.0, 0.0, 100.0], [0.0; 3])),
        ("red sat -100", c([0.0; 3], [-100.0, 0.0, 0.0])),
        ("green sat 60", c([0.0; 3], [0.0, 60.0, 0.0])),
        ("blue sat 100", c([0.0; 3], [0.0, 0.0, 100.0])),
        ("all primaries", c([30.0, -40.0, 20.0], [-20.0, 50.0, -60.0])),
        ("out of range clamps", c([150.0, -130.0, 0.0], [0.0, -150.0, 120.0])),
        ("after balance", CameraRaw { temperature: 40.0, tint: -15.0, exposure: 0.8, ..c([-25.0, 35.0, -45.0], [40.0, -30.0, 25.0]) }),
        ("after exposure 2", CameraRaw { exposure: 2.0, ..c([20.0, 20.0, 20.0], [30.0, 30.0, 30.0]) }),
    ]
}

pub fn run() {
    println!("// PhotoCraft {COMMIT} crates/algo/src/camera_raw.rs stage 1b (calibrate, calibration_weights).");
    println!("// Pixels: develop(float = false), sRGB encoding, the per-pixel inputs of camera_raw_per_pixel_vectors.inc.");
    println!("// Generated by tools/photocraft_vectors calibration -- do not edit.");
    println!("struct CalibrationCase {{ const char* name; float temperature, tint, exposure, hue[3], sat[3]; std::vector<float> in, out; }};");
    println!("const CalibrationCase kCalibration[] = {{");
    let src = inputs();
    let input: Vec<f32> = src.iter().flat_map(|c| *c).collect();
    for (name, p) in cases() {
        let mut px: Vec<[f32; 4]> = src.iter().map(|c| [c[0], c[1], c[2], 1.0]).collect();
        let n = px.len();
        develop(&mut px, n, 1, &p, false);
        let out: Vec<f32> = px.iter().flat_map(|q| [q[0], q[1], q[2]]).collect();
        println!(
            "{{\"{name}\", {}, {}, {}, {{{}}}, {{{}}}, {{{}}}, {{{}}}}},",
            f(p.temperature), f(p.tint), f(p.exposure), list(&p.calibration_hue), list(&p.calibration_sat), list(&input), list(&out)
        );
    }
    println!("}};");
    println!("// calibration_weights(h) for h = -30, 0, 15, ..., 375: red, green, blue.");
    println!("const float kCalibrationWeights[][4] = {{");
    let mut h = -30.0f32;
    while h <= 375.0 {
        let w = calibration_weights(h);
        println!("{{{}, {}}},", f(h), list(&w));
        h += 15.0;
    }
    println!("}};");
}
