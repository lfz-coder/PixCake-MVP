//! `detail` mode: PhotoCraft's Camera Raw stage 8 (noise reduction on luminance and chroma,
//! sharpening on luminance) on the frames of `spatial`, for PixCake's port in
//! gpu/render/src/camera_raw_spatial.cpp.  Only Detail sliders are set, so develop runs stage 8
//! and the final clip to 0..1.

use photocraft_algo::camera_raw::{CameraRaw, develop};

use crate::{COMMIT, f};

fn short(v: &[f32]) -> String {
    v.iter().map(|x| format!("{x:e}f")).collect::<Vec<_>>().join(",")
}

fn cases() -> Vec<(&'static str, CameraRaw)> {
    let c = |f: &dyn Fn(&mut CameraRaw)| {
        let mut p = CameraRaw::default();
        f(&mut p);
        p
    };
    vec![
        ("sharpen 100", c(&|p| p.sharpen_amount = 100.0)),
        ("sharpen 150 radius 3 detail 100", c(&|p| {
            p.sharpen_amount = 150.0;
            p.sharpen_radius = 3.0;
            p.sharpen_detail = 100.0;
        })),
        ("sharpen 60 radius 0.5 detail 0", c(&|p| {
            p.sharpen_amount = 60.0;
            p.sharpen_radius = 0.5;
            p.sharpen_detail = 0.0;
        })),
        ("sharpen radius clamped", c(&|p| {
            p.sharpen_amount = 80.0;
            p.sharpen_radius = 5.0;
        })),
        ("sharpen 80 masking 50", c(&|p| {
            p.sharpen_amount = 80.0;
            p.sharpen_masking = 50.0;
        })),
        ("sharpen 120 masking 100", c(&|p| {
            p.sharpen_amount = 120.0;
            p.sharpen_masking = 100.0;
        })),
        ("luminance nr 60", c(&|p| p.noise_luminance = 60.0)),
        ("luminance nr 100 detail 0", c(&|p| {
            p.noise_luminance = 100.0;
            p.noise_luminance_detail = 0.0;
        })),
        ("color nr 50", c(&|p| p.noise_color = 50.0)),
        ("color nr 100 detail 100", c(&|p| {
            p.noise_color = 100.0;
            p.noise_color_detail = 100.0;
        })),
        ("all", c(&|p| {
            p.noise_luminance = 40.0;
            p.noise_luminance_detail = 30.0;
            p.noise_color = 60.0;
            p.noise_color_detail = 20.0;
            p.sharpen_amount = 90.0;
            p.sharpen_radius = 1.5;
            p.sharpen_detail = 60.0;
            p.sharpen_masking = 20.0;
        })),
        ("all scale 0.5", c(&|p| {
            p.noise_luminance = 70.0;
            p.noise_color = 40.0;
            p.sharpen_amount = 100.0;
            p.sharpen_radius = 2.0;
            p.sharpen_masking = 30.0;
            p.pixel_scale = 0.5;
        })),
        ("all scale 0.25", c(&|p| {
            p.noise_luminance = 100.0;
            p.noise_color = 100.0;
            p.sharpen_amount = 150.0;
            p.pixel_scale = 0.25;
        })),
    ]
}

pub fn run() {
    println!("// PhotoCraft {COMMIT} crates/algo/src/camera_raw.rs develop (float = false), sRGB encoding:");
    println!("// stage 8 (detail) only, on the frames of tools/photocraft_vectors/src/spatial.rs frames() (not \"long\");");
    println!("// the 840 x 6 strip keeps every 15th pixel.  Generated by tools/photocraft_vectors detail -- do not edit.");
    println!("struct DetailCase {{ const char* frame; const char* name; float sharpen_amount, sharpen_radius, sharpen_detail, sharpen_masking, noise_luminance, noise_luminance_detail, noise_color, noise_color_detail, pixel_scale; int stride; std::vector<float> out; }};");
    println!("const DetailCase kDetail[] = {{");
    for (frame, w, h, pixel) in crate::spatial::frames() {
        if frame == "long" {
            continue;
        }
        for (name, p) in cases() {
            let mut px: Vec<[f32; 4]> = (0..w * h).map(|i| pixel(i % w, i / w, w, h)).collect();
            develop(&mut px, w, h, &p, false);
            let stride = if w * h > 2000 { 15 } else { 1 };
            let out: Vec<f32> = px.iter().step_by(stride).flat_map(|q| [q[0], q[1], q[2]]).collect();
            let s = [
                p.sharpen_amount, p.sharpen_radius, p.sharpen_detail, p.sharpen_masking, p.noise_luminance,
                p.noise_luminance_detail, p.noise_color, p.noise_color_detail, p.pixel_scale,
            ]
            .map(f);
            println!("{{\"{frame}\", \"{name}\", {}, {stride}, {{{}}}}},", s.join(", "), short(&out));
        }
    }
    println!("}};");
}
