//! `adjust` mode: PhotoCraft's Photoshop adjustment-layer functions (crates/compose) that PixCake
//! ports in gpu/render/src/adjust.cpp -- Levels tables, Selective Color, 3D LUT sampling and the
//! normal / multiply / screen composite -- as C++ initializer lists.

use photocraft_color::blend::BlendMode;
use photocraft_compose::adjust::{lut3d_sample, selective_color, tone_luts_q};
use photocraft_compose::psblend::composite;
use photocraft_doc::Adjustment;
use photocraft_doc::adjust::{LevelsChannel, ToneSpace};

use crate::{COMMIT, f, inputs, list};

fn levels_cases() -> Vec<(&'static str, LevelsChannel)> {
    let ch = |in_black: f32, in_white: f32, gamma: f32, out_black: f32, out_white: f32| LevelsChannel { in_black, in_white, gamma, out_black, out_white };
    vec![
        ("identity", ch(0.0, 1.0, 1.0, 0.0, 1.0)),
        ("gamma 0.5", ch(0.0, 1.0, 0.5, 0.0, 1.0)),
        ("gamma 1.3", ch(0.0, 1.0, 1.3, 0.0, 1.0)),
        ("gamma 2.0", ch(0.0, 1.0, 2.0, 0.0, 1.0)),
        ("gamma 9.99", ch(0.0, 1.0, 9.99, 0.0, 1.0)),
        ("44..214 out 48..255", ch(44.0 / 255.0, 214.0 / 255.0, 1.0, 48.0 / 255.0, 1.0)),
        ("all", ch(20.0 / 255.0, 230.0 / 255.0, 10f32.powf(0.3), 10.0 / 255.0, 240.0 / 255.0)),
    ]
}

/// The deterministic 17^3 table the LUT vectors sample (red fastest).
pub fn lut_table(n: usize) -> Vec<f32> {
    let mut t = Vec::with_capacity(n * n * n * 3);
    for b in 0..n {
        for g in 0..n {
            for r in 0..n {
                let c = [r, g, b].map(|v| v as f32 / (n - 1) as f32);
                t.push((c[1] + 0.1 * (6.0 * c[0]).sin()).clamp(0.0, 1.0));
                t.push((c[2] + 0.1 * (5.0 * c[1]).cos()).clamp(0.0, 1.0));
                t.push((c[0] * 0.8 + 0.1).clamp(0.0, 1.0));
            }
        }
    }
    t
}

pub fn run() {
    println!("// PhotoCraft {COMMIT} crates/compose: tone_luts_q (Levels, quantum 255), selective_color,");
    println!("// lut3d_sample and psblend::composite.  Generated by tools/photocraft_vectors adjust -- do not edit.");
    println!("// table: the 4096-entry LUT row at every 8th entry (512 samples, index 8k).");
    println!("struct LevelsCase {{ const char* name; float in_black, in_white, gamma, out_black, out_white; float table[512]; }};");
    println!("const LevelsCase kLevels[] = {{");
    for (name, ch) in levels_cases() {
        let adj = Adjustment::Levels { master: ch.clone(), per_channel: std::array::from_fn(|_| LevelsChannel::default()), space: ToneSpace::Rgb, black: LevelsChannel::default() };
        let rows = tone_luts_q(&adj, Some(255.0));
        println!("{{\"{name}\", {}, {}, {}, {}, {}, {{{}}}}},", f(ch.in_black), f(ch.in_white), f(ch.gamma), f(ch.out_black), f(ch.out_white), list(&rows[0].iter().step_by(8).copied().collect::<Vec<f32>>()));
    }
    println!("}};");

    println!("struct SelectiveCase {{ int target; int ink; float amount; bool relative; float in[3]; float out[3]; }};");
    println!("const SelectiveCase kSelective[] = {{");
    for target in 0..9 {
        for ink in 0..4 {
            for amount in [-100.0f32, 100.0] {
                for relative in [true, false] {
                    let mut adj = [[0.0f32; 4]; 9];
                    adj[target][ink] = amount;
                    for c in inputs().into_iter().step_by(3) {
                        let o = selective_color(c, relative, &adj);
                        println!("{{{target}, {ink}, {}, {relative}, {{{}}}, {{{}}}}},", f(amount), list(&c), list(&o));
                    }
                }
            }
        }
    }
    println!("}};");

    println!("struct LutCase {{ bool tetrahedral; float in[3]; float out[3]; }};");
    println!("const LutCase kLut[] = {{");
    let table = lut_table(17);
    for tetrahedral in [false, true] {
        for c in inputs() {
            let o = lut3d_sample(&table, 17, c, tetrahedral);
            println!("{{{tetrahedral}, {{{}}}, {{{}}}}},", list(&c), list(&o));
        }
    }
    println!("}};");

    println!("struct CompositeCase {{ int mode; float opacity; float backdrop[4]; float source[4]; float out[4]; }};");
    println!("const CompositeCase kComposite[] = {{");
    let colours = [[0.1f32, 0.5, 0.9], [0.9, 0.2, 0.3], [0.5, 0.5, 0.5], [1.0, 1.0, 1.0]];
    for (m, mode) in [BlendMode::Normal, BlendMode::Multiply, BlendMode::Screen].into_iter().enumerate() {
        for ab in [0.0f32, 0.5, 1.0] {
            for as_ in [0.5f32, 1.0] {
                for opacity in [0.3f32, 1.0] {
                    for cb in colours {
                        for cs in colours {
                            let b = [cb[0], cb[1], cb[2], ab];
                            let s = [cs[0], cs[1], cs[2], as_];
                            let o = composite(mode, b, s, opacity);
                            println!("{{{m}, {}, {{{}}}, {{{}}}, {{{}}}}},", f(opacity), list(&b), list(&s), list(&o));
                        }
                    }
                }
            }
        }
    }
    println!("}};");
}
