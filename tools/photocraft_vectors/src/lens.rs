//! `lens` mode: PhotoCraft's Lens Correction filter (crates/algo/src/lens.rs `correct`: the
//! inverse map with Remove Distortion and the manual Vignette Amount / Midpoint, bicubic
//! resampling, premultiplied alpha, edge modes) on 32-bit RGBA surfaces, for PixCake's port in
//! gpu/render/src/lens.cpp.  Frames: the spatial frames, opaque, and the 24 x 16 "detail" frame
//! with a varying alpha ("alpha").

use photocraft_algo::lens::{EdgeMode, LensCorrection, correct};
use photocraft_color::{ColorMode, PixelFormat, SampleType};
use photocraft_geom::Rect;
use photocraft_raster::Surface;

use crate::{COMMIT, f};

fn short(v: &[f32]) -> String {
    v.iter().map(|x| format!("{x:e}f")).collect::<Vec<_>>().join(",")
}

fn cases() -> Vec<(&'static str, LensCorrection)> {
    let c = |distortion: f64, amount: f64, midpoint: f64, edge: EdgeMode| LensCorrection {
        distortion,
        vignette_amount: amount,
        vignette_midpoint: midpoint,
        edge,
        ..LensCorrection::default()
    };
    vec![
        ("vignette -100", c(0.0, -100.0, 50.0, EdgeMode::Transparency)),
        ("vignette 100", c(0.0, 100.0, 50.0, EdgeMode::Transparency)),
        ("vignette -60 mid 0", c(0.0, -60.0, 0.0, EdgeMode::Transparency)),
        ("vignette 40 mid 100", c(0.0, 40.0, 100.0, EdgeMode::Transparency)),
        ("vignette -30 mid 75", c(0.0, -30.0, 75.0, EdgeMode::Extension)),
        ("identity", c(0.0, 0.0, 50.0, EdgeMode::Transparency)),
        ("distortion 50", c(50.0, 0.0, 50.0, EdgeMode::Transparency)),
        ("distortion -60", c(-60.0, 0.0, 50.0, EdgeMode::Transparency)),
        ("distortion -60 extension", c(-60.0, 0.0, 50.0, EdgeMode::Extension)),
        ("distortion 100 vignette -50", c(100.0, -50.0, 30.0, EdgeMode::Transparency)),
    ]
}

pub fn run() {
    println!("// PhotoCraft {COMMIT} crates/algo/src/lens.rs correct() on RGBA F32 surfaces (no profile).");
    println!("// Frames: tools/photocraft_vectors/src/spatial.rs frames() but \"long\" (strip: every 15th pixel), and \"alpha\".");
    println!("// Generated by tools/photocraft_vectors lens -- do not edit.");
    println!("struct LensCase {{ const char* frame; const char* name; float distortion, amount, midpoint; bool extension; int stride; std::vector<float> out; }};");
    println!("const LensCase kLens[] = {{");
    let mut frames: Vec<(&str, usize, usize, Box<dyn Fn(usize, usize) -> [f32; 4]>)> = Vec::new();
    for (name, w, h, pixel) in crate::spatial::frames() {
        if name != "long" {
            frames.push((name, w, h, Box::new(move |x, y| pixel(x, y, w, h))));
        }
    }
    let (dw, dh, detail) = {
        let f = crate::spatial::frames();
        (f[0].1, f[0].2, f[0].3)
    };
    frames.push(("alpha", dw, dh, Box::new(move |x, y| {
        let mut p = detail(x, y, dw, dh);
        p[3] = [1.0, 0.6, 0.0, 0.25][(x + 2 * y) % 4];
        p
    })));
    for (frame, w, h, pixel) in &frames {
        for (name, lc) in cases() {
            let fmt = PixelFormat::new(ColorMode::Rgb, SampleType::F32, true);
            let mut s = Surface::new(fmt);
            let rect = Rect::new(0, 0, *w as i32, *h as i32);
            let data: Vec<f32> = (0..w * h).flat_map(|i| pixel(i % w, i / w)).collect();
            s.write_region(rect, &data);
            let out = correct(&s, rect, &lc).read_region(rect);
            let stride = if w * h > 2000 { 15 } else { 1 };
            let kept: Vec<f32> = out.chunks_exact(4).step_by(stride).flatten().copied().collect();
            let extension = matches!(lc.edge, EdgeMode::Extension);
            println!(
                "{{\"{frame}\", \"{name}\", {}, {}, {}, {extension}, {stride}, {{{}}}}},",
                f(lc.distortion as f32), f(lc.vignette_amount as f32), f(lc.vignette_midpoint as f32), short(&kept)
            );
        }
    }
    println!("}};");
}
