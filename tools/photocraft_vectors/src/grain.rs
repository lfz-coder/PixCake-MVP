//! `grain` mode: PhotoCraft's Camera Raw stage 9 (grain) on a 12 x 12 image, which PixCake ports
//! in gpu/render/src/camera_raw.cpp.  Only grain is set, so develop runs that stage and the final
//! clip to 0..1.

use photocraft_algo::camera_raw::{CameraRaw, develop};

use crate::{COMMIT, f, list};

pub const SIDE: usize = 12;

pub fn image() -> Vec<[f32; 4]> {
    (0..SIDE * SIDE).map(|i| [0.2 + 0.6 * (i % SIDE) as f32 / (SIDE - 1) as f32, 0.15 + 0.7 * (i / SIDE) as f32 / (SIDE - 1) as f32, 0.5, 1.0]).collect()
}

pub fn run() {
    println!("// PhotoCraft {COMMIT} crates/algo/src/camera_raw.rs develop, grain only, sRGB encoding, float = false.");
    println!("// Image: pixel (x, y) of a {SIDE} x {SIDE} frame is (0.2 + 0.6 x / 11, 0.15 + 0.7 y / 11, 0.5).");
    println!("// Generated by tools/photocraft_vectors grain -- do not edit.");
    println!("struct GrainCase {{ float amount, size, roughness, pixel_scale; unsigned seed; float out[{}]; }};", SIDE * SIDE * 3);
    println!("const GrainCase kGrain[] = {{");
    for amount in [20.0f32, 100.0] {
        for size in [0.0f32, 25.0, 100.0] {
            for roughness in [0.0f32, 50.0, 100.0] {
                for (pixel_scale, seed) in [(1.0f32, 0u32), (0.25, 0), (1.0, 12345)] {
                    let p = CameraRaw { grain_amount: amount, grain_size: size, grain_roughness: roughness, pixel_scale, seed, ..CameraRaw::default() };
                    let mut px = image();
                    develop(&mut px, SIDE, SIDE, &p, false);
                    let out: Vec<f32> = px.iter().flat_map(|q| [q[0], q[1], q[2]]).collect();
                    println!("{{{}, {}, {}, {}, {seed}u, {{{}}}}},", f(amount), f(size), f(roughness), f(pixel_scale), list(&out));
                }
            }
        }
    }
    println!("}};");
}
