//! `curves` mode: PhotoCraft's Camera Raw stage 5 (parametric tone curve, then the master, red,
//! green and blue point curves), which PixCake ports in gpu/render/src/camera_raw.cpp.
//! Tables come from `per_pixel` (its `parametric` and `point` LUTs, every 4th entry and the last);
//! pixels from `develop` with float = false, so values above 1 after Exposure take `lut_eval`'s
//! linear extension before the final clip.

use photocraft_algo::camera_raw::{CURVE_LUT, CameraRaw, develop, per_pixel};

use crate::{COMMIT, f, inputs, list};

type Points = Vec<[f32; 2]>;

fn cases() -> Vec<(&'static str, CameraRaw)> {
    let p = |h: f32, l: f32, d: f32, s: f32| CameraRaw { curve_highlights: h, curve_lights: l, curve_darks: d, curve_shadows: s, ..CameraRaw::default() };
    let pts = |master: Points, r: Points, g: Points, b: Points| CameraRaw {
        point_curve: master,
        point_curve_red: r,
        point_curve_green: g,
        point_curve_blue: b,
        ..CameraRaw::default()
    };
    let s_curve: Points = vec![[0.0, 0.0], [64.0, 40.0], [192.0, 220.0], [255.0, 255.0]];
    vec![
        ("parametric highlights 60", p(60.0, 0.0, 0.0, 0.0)),
        ("parametric all", p(-40.0, 30.0, -25.0, 50.0)),
        ("parametric extremes", p(100.0, -100.0, 100.0, -100.0)),
        ("parametric splits", CameraRaw { curve_splits: [10.0, 40.0, 90.0], ..p(50.0, -50.0, 50.0, -50.0) }),
        ("parametric splits clamped", CameraRaw { curve_splits: [0.0, 50.0, 100.0], ..p(80.0, 20.0, -20.0, -80.0) }),
        ("master s-curve", pts(s_curve.clone(), vec![], vec![], vec![])),
        ("master lifted black", pts(vec![[0.0, 30.0], [255.0, 255.0]], vec![], vec![], vec![])),
        ("master flat segment", pts(vec![[0.0, 0.0], [80.0, 100.0], [160.0, 100.0], [255.0, 255.0]], vec![], vec![], vec![])),
        ("master steep", pts(vec![[0.0, 0.0], [30.0, 200.0], [60.0, 210.0], [255.0, 255.0]], vec![], vec![], vec![])),
        ("master inverted", pts(vec![[0.0, 255.0], [255.0, 0.0]], vec![], vec![], vec![])),
        ("master inner points", pts(vec![[40.0, 10.0], [128.0, 140.0], [220.0, 250.0]], vec![], vec![], vec![])),
        ("master unsorted", pts(vec![[192.0, 220.0], [0.0, 0.0], [255.0, 255.0], [64.0, 40.0]], vec![], vec![], vec![])),
        ("rgb channels", pts(vec![], vec![[0.0, 20.0], [128.0, 150.0], [255.0, 240.0]], vec![[0.0, 0.0], [100.0, 90.0], [255.0, 255.0]], vec![[0.0, 0.0], [128.0, 100.0], [255.0, 230.0]])),
        ("all curves", CameraRaw { curve_shadows: 30.0, curve_highlights: -20.0, ..pts(s_curve.clone(), vec![[0.0, 10.0], [255.0, 255.0]], vec![], vec![[0.0, 0.0], [255.0, 235.0]]) }),
        ("exposure then curves", CameraRaw { exposure: 1.5, curve_lights: 40.0, ..pts(s_curve.clone(), vec![], vec![], vec![]) }),
        ("presence curves hsl", CameraRaw { vibrance: 30.0, hsl_hue: [20.0, 0.0, 0.0, 0.0, -30.0, 0.0, 0.0, 0.0], curve_darks: -30.0, ..pts(s_curve, vec![], vec![[0.0, 0.0], [128.0, 150.0], [255.0, 255.0]], vec![]) }),
    ]
}

fn points(c: &Points) -> String {
    let v: Vec<f32> = c.iter().flat_map(|p| [p[0], p[1]]).collect();
    format!("{{{}}}", list(&v))
}

fn sampled(lut: &Option<Vec<f32>>) -> String {
    match lut {
        None => "{}".into(),
        Some(t) => {
            assert_eq!(t.len(), CURVE_LUT);
            let mut v: Vec<f32> = t.iter().step_by(4).copied().collect();
            v.push(t[CURVE_LUT - 1]);
            format!("{{{}}}", list(&v))
        }
    }
}

pub fn run() {
    println!("// PhotoCraft {COMMIT} crates/algo/src/camera_raw.rs stage 5 (parametric_lut, curve_lut, lut_eval).");
    println!("// Tables: per_pixel's LUTs ({CURVE_LUT} entries), entries 0, 4, ..., 1020 and 1023; empty when off.");
    println!("// Pixels: develop(float = false), sRGB encoding, the per-pixel inputs of camera_raw_per_pixel_vectors.inc.");
    println!("// Generated by tools/photocraft_vectors curves -- do not edit.");
    println!("struct CurveCase {{");
    println!("  const char* name;");
    println!("  float exposure, vibrance, hue_red, hue_aqua;");
    println!("  float highlights, lights, darks, shadows, splits[3];");
    println!("  std::vector<float> master, red, green, blue;  // x0, y0, x1, y1, ...");
    println!("  std::vector<float> parametric_lut, master_lut, red_lut, green_lut, blue_lut;");
    println!("  std::vector<float> in, out;  // rgb triples");
    println!("}};");
    println!("const CurveCase kCurves[] = {{");
    let src = inputs();
    let input: Vec<f32> = src.iter().flat_map(|c| *c).collect();
    for (name, p) in cases() {
        let pp = per_pixel(&p, src.len(), 1, false, None).expect("per-pixel settings");
        let mut px: Vec<[f32; 4]> = src.iter().map(|c| [c[0], c[1], c[2], 1.0]).collect();
        let n = px.len();
        develop(&mut px, n, 1, &p, false);
        let out: Vec<f32> = px.iter().flat_map(|q| [q[0], q[1], q[2]]).collect();
        println!(
            "{{\"{name}\", {}, {}, {}, {}, {}, {}, {}, {}, {{{}}}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {{{}}}, {{{}}}}},",
            f(p.exposure), f(p.vibrance), f(p.hsl_hue[0]), f(p.hsl_hue[4]),
            f(p.curve_highlights), f(p.curve_lights), f(p.curve_darks), f(p.curve_shadows), list(&p.curve_splits),
            points(&p.point_curve), points(&p.point_curve_red), points(&p.point_curve_green), points(&p.point_curve_blue),
            sampled(&pp.parametric), sampled(&pp.point[0]), sampled(&pp.point[1]), sampled(&pp.point[2]), sampled(&pp.point[3]),
            list(&input), list(&out)
        );
    }
    println!("}};");
}
